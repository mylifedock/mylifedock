#!/usr/bin/env node

/**
 * MyLifeDock License Signing Key Pair Generator
 *
 * Creates the RSA-2048 key pair used to sign Pro license keys.
 *
 *   - The PRIVATE key is written OUTSIDE the repository (default:
 *     ~/.mylifedock/license-signing-private-key.pem). Never commit it.
 *     Copy its contents into the Apps Script property MLD_LICENSE_PRIVATE_KEY.
 *   - The PUBLIC key is written into src/config/licenseConfig.ts so the app
 *     can verify licenses offline. It is not secret.
 *
 * Rotating the key pair invalidates every license signed with the old key.
 *
 * Usage:
 *   node scripts/generate-license-keypair.cjs [--out <private-key-path>] [--force]
 */

const crypto = require("crypto");
const fs = require("fs");
const os = require("os");
const path = require("path");

const args = process.argv.slice(2);
const force = args.includes("--force");
const outIndex = args.indexOf("--out");
const privateKeyPath = outIndex !== -1 && args[outIndex + 1]
  ? path.resolve(args[outIndex + 1])
  : path.join(os.homedir(), ".mylifedock", "license-signing-private-key.pem");

const repoRoot = path.resolve(__dirname, "..");
if (privateKeyPath.startsWith(repoRoot + path.sep)) {
  console.error("Refusing to write the private key inside the repository. Choose a path outside it.");
  process.exit(1);
}

if (fs.existsSync(privateKeyPath) && !force) {
  console.error(`A private key already exists at ${privateKeyPath}.`);
  console.error("Re-run with --force to replace it (this invalidates all existing licenses).");
  process.exit(1);
}

const { publicKey, privateKey } = crypto.generateKeyPairSync("rsa", {
  modulusLength: 2048,
  publicKeyEncoding: { type: "spki", format: "der" },
  privateKeyEncoding: { type: "pkcs8", format: "pem" },
});

fs.mkdirSync(path.dirname(privateKeyPath), { recursive: true });
fs.writeFileSync(privateKeyPath, privateKey, { mode: 0o600 });

const spkiBase64 = publicKey.toString("base64");
const configPath = path.join(repoRoot, "src", "config", "licenseConfig.ts");
fs.writeFileSync(
  configPath,
  `/**
 * Public key (base64 SPKI, RSASSA-PKCS1-v1_5 / SHA-256) used to verify
 * MyLifeDock Pro license signatures offline. Not secret.
 *
 * Generated by scripts/generate-license-keypair.cjs. The matching private key
 * is kept outside the repository and must never be committed.
 */
export const LICENSE_PUBLIC_KEY_SPKI =
  "${spkiBase64}";
`,
);

// Keep the local admin tool's verifier in sync with the app.
const adminPath = path.join(repoRoot, "tools", "admin.html");
if (fs.existsSync(adminPath)) {
  const adminHtml = fs.readFileSync(adminPath, "utf8");
  fs.writeFileSync(
    adminPath,
    adminHtml.replace(/const LICENSE_PUBLIC_KEY_SPKI = "[^"]*";/, `const LICENSE_PUBLIC_KEY_SPKI = "${spkiBase64}";`),
  );
}

console.log(`Private key written to: ${privateKeyPath}`);
console.log(`Public key written to:  ${path.relative(repoRoot, configPath)} and tools/admin.html`);
console.log("\nNext: copy the private key file contents into the Apps Script");
console.log("Script Property MLD_LICENSE_PRIVATE_KEY (see scripts/razorpay-auto-mailer.gs).");
